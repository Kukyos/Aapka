def term(value: Any) -> str:
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, list):
        return ", ".join(term(v) for v in value) or "none"
    if isinstance(value, dict) and "n" in value:
        n, unit = value["n"], value["unit"]
        return f"{n} {unit[:-1] if n == 1 else unit}"
    return CLINICAL_TERMS.get(str(value), str(value).replace("_", " "))


def _get(session: Session, slot: str) -> Any:
    value = session.slots.get(slot)
    return None if value in (None, [], "") else value


def _proxy_note(session: Session) -> str | None:
    """Requirement R1. A history given by someone else is a different clinical fact,
    and the doctor has to see that before reading a word of it."""
    respondent = session.slots.get("identity.respondent")
    if respondent and respondent != "self":
        return f"History given by {term(respondent)}, not the patient."
    return None


# ---------------------------------------------------------------- HPI prose

_HPI_SYSTEM = (
    "You turn structured intake fields into ONE short clinical sentence for a busy "
    "physician.\n"
    "Absolute rules:\n"
    "1. Use ONLY the facts given. Adding anything not listed is a serious error.\n"
    "2. Never name, suggest, or imply a diagnosis. You are writing a history.\n"
    "3. One or two sentences, under 45 words, plain clinical English.\n"
    "4. No preamble, no heading. Output the sentence only."
)


def _hpi_deterministic(session: Session) -> str:
    """The sentence that is always available, with or without a model."""
    bits = []
    site = _get(session, "hpi.site")
    character = _get(session, "hpi.character")
    complaint = _get(session, "cc.primary")
    duration = _get(session, "hpi.duration")

    lead = term(complaint) if complaint else "Presenting complaint"
    if site:
        lead = f"{term(site).capitalize()} {('pain' if 'pain' in str(complaint) else str(term(complaint)))}"
    if character:
        lead += f", {term(character)} in character"
    if duration:
        lead += f", for {term(duration)}"
    bits.append(lead)

    onset = _get(session, "hpi.onset")
    if onset and onset != "unsure":
        bits.append(term(onset))
    radiation = _get(session, "hpi.radiation")
    if radiation and radiation != "none":
        bits.append(f"radiating {term(radiation)}")
    timing = _get(session, "hpi.timing")
    if timing:
        bits.append(term(timing))
    severity = _get(session, "hpi.severity")
    if severity is not None:
        bits.append(f"severity {severity}/10")
    progression = _get(session, "hpi.progression")
    if progression:
        bits.append(term(progression))

    sentence = "; ".join(bits) + "."

    associated = _get(session, "hpi.associated")
    if associated and associated != ["none"]:
        sentence += f" Associated with {term([a for a in associated if a != 'none'])}."
    aggravating = _get(session, "hpi.aggravating")
    relieving = _get(session, "hpi.relieving")
    if aggravating and aggravating != ["nothing_particular"]:
        sentence += f" Worse with {term([a for a in aggravating if a != 'nothing_particular'])}."
    if relieving and relieving != ["nothing_helps"]:
        sentence += f" Relieved by {term([r for r in relieving if r != 'nothing_helps'])}."
    elif relieving == ["nothing_helps"]:
        sentence += " No relieving factor reported."

    first = _get(session, "hpi.first_episode")
    if first is False:
        sentence += " Not the first episode."
    return sentence


def _no_new_symptoms(text: str, facts: str) -> bool:
    """Reject a rewrite that smuggled in a word the facts never contained.

    Crude on purpose. It cannot catch every fabrication, but it catches the failure
    mode that matters — a model helpfully adding 'radiating to the left arm' — and it
    fails closed to the deterministic sentence, which is never wrong.
    """
    risky = {
        "radiat", "diagnos", "likely", "suggest", "consistent with", "rule out",
        "probable", "impression", "differential", "recommend", "advise", "should",
    }
    lowered = text.lower()
    facts_lower = facts.lower()
    return not any(word in lowered and word not in facts_lower for word in risky)


def hpi_paragraph(session: Session, *, use_llm: bool = True) -> tuple[str, str]:
    """Returns (paragraph, how) where how is 'template' or a provider name."""
    baseline = _hpi_deterministic(session)
    if not use_llm:
        return baseline, "template"

    facts = "\n".join(
        f"- {slot}: {term(value)}"
        for slot, value in session.slots.items()
        if slot.startswith(("cc.", "hpi.")) and value not in (None, [], "")
    )
    parsed = llm.chat(
        [
            {"role": "system", "content": _HPI_SYSTEM},
            {"role": "user", "content": f"Facts:\n{facts}\n\nWrite the sentence."},
        ],
        temperature=0.1,
    )
    if parsed.ok and parsed.text.strip():
        candidate = parsed.text.strip().strip('"')
        if len(candidate) < 400 and _no_new_symptoms(candidate, facts + baseline):
            return candidate, parsed.provider
    return baseline, "template"


# ---------------------------------------------------------------- assembly


def build(
    ont: Ontology,
    session: Session,
    timeline: dict[str, Any] | None = None,
    *,
    use_llm: bool = True,
) -> dict[str, Any]:
    """The whole summary, in the brief's section order."""
    from .engine import coverage  # local import keeps engine.py free of this module

    paragraph, how = hpi_paragraph(session, use_llm=use_llm)
    sections: list[dict[str, Any]] = []

    def add(key: str, title: str, lines: list[str], note: str | None = None) -> None:
        sections.append(
            {"key": key, "title": title, "lines": [l for l in lines if l], "note": note}
        )

    # 1 — Chief complaint
    complaint_lines = []
    if _get(session, "cc.primary"):
        complaint_lines.append(term(session.slots["cc.primary"]).capitalize())
    if _get(session, "hpi.duration"):
        complaint_lines[-1] = f"{complaint_lines[-1]} for {term(session.slots['hpi.duration'])}"
    narration = _get(session, "cc.narration")
    add(
        "cc",
        "Chief complaint",
        complaint_lines,
        note=f'In the patient\'s own words: "{narration}"' if narration else None,
    )

    # 2 — HPI
    add("hpi", "History of present illness", [paragraph])

    # 3 — Past medical and surgical
    past = []
    conditions = _get(session, "past.conditions")
    if conditions:
        past.append(
            "Known: " + term([c for c in conditions if c != "none"])
            if conditions != ["none"]
            else "No known chronic illness"
        )
    if _get(session, "past.surgeries") is True:
        detail = _get(session, "past.surgeries_detail")
        past.append(f"Previous surgery: {detail}" if detail else "Previous surgery (details not given)")
    elif session.slots.get("past.surgeries") is False:
        past.append("No previous surgery")
    if _get(session, "past.hospitalisation"):
        past.append(f"Last admission: {term(session.slots['past.hospitalisation'])}")
    add("past", "Past medical & surgical history", past)

    # 4 — Drug and allergy
    drugs = []
    if session.slots.get("drugs.taking_now") is True:
        systems = [s for s in (_get(session, "drugs.systems") or []) if s != "none"]
        line = "Currently on medication"
        if systems:
            line += f" ({term(systems)})"
        if _get(session, "drugs.adherence"):
            line += f", adherence {term(session.slots['drugs.adherence'])}"
        drugs.append(line)
    elif session.slots.get("drugs.taking_now") is False:
        drugs.append("Not on any medication")
    allergy = _get(session, "drugs.allergy_known")
    if allergy == "none":
        drugs.append("No known allergies")
    elif allergy:
        detail = _get(session, "drugs.allergy_detail")
        drugs.append(f"ALLERGY: {term(allergy)}" + (f" — {detail}" if detail else ""))
    add("drugs", "Drug & allergy history", drugs)

    # 5 — Family
    family = _get(session, "family.conditions")
    add(
        "family",
        "Family history",
        [
            "No relevant family history"
            if family == ["none"]
            else (f"Family history of {term([f for f in family if f != 'none'])}" if family else "")
        ],
    )

    # 6 — Personal
    personal = []
    for slot, label in [
        ("personal.diet", "Diet"), ("personal.tobacco", "Tobacco"),
        ("personal.alcohol", "Alcohol"), ("personal.sleep", "Sleep"),
        ("personal.bowel", "Bowels"), ("personal.occupation_strain", "Occupation"),
        ("personal.menstrual", "Menstrual"),
    ]:
        if _get(session, slot):
            personal.append(f"{label}: {term(session.slots[slot])}")
    add("personal", "Personal history", personal)

    # 7 — Review of systems
    ros = []
    danger = _get(session, "ros.danger_signs")
    if danger and danger != ["none"]:
        ros.append("DANGER SIGNS REPORTED: " + term([d for d in danger if d != "none"]))
    elif danger == ["none"]:
        ros.append("Danger-sign screen negative")
    for slot, label in [
        ("ros.general", "General"), ("ros.cardioresp", "Cardiorespiratory"),
        ("ros.gi", "Gastrointestinal"), ("ros.neuro", "Neurological"),
        ("ros.uro", "Genitourinary"),
    ]:
        value = _get(session, slot)
        if value and value != ["none"]:
            ros.append(f"{label}: {term([v for v in value if v != 'none'])}")
    if not any(l.startswith(("General", "Cardio", "Gastro", "Neuro", "Genito")) for l in ros):
        ros.append("Systems review not reached within the interview budget")
    add("ros", "Review of systems", ros)

    # 8 — AYUSH. Placed after the mandated core sections so the standard history is
    # never displaced, and rendered with its provenance attached.
    if session.mode == "ayush":
        ayush = []
        prakriti = _get(session, "ayush.prakriti_screen")
        if prakriti:
            counts: dict[str, int] = {}
            for item in prakriti:
                dosha = DOSHA_OF.get(item)
                if dosha:
                    counts[dosha] = counts.get(dosha, 0) + 1
            if counts:
                ranked = sorted(counts.items(), key=lambda kv: -kv[1])
                ayush.append(
                    "Prakriti screen (abbreviated, patient-reported): "
                    + ", ".join(f"{d} {n}/3" for d, n in ranked)
                )
        for slot, label in [
            ("ayush.vikriti", "Vikriti"), ("ayush.sara", "Sara"),
            ("ayush.samhanana", "Samhanana"), ("ayush.pramana", "Pramana"),
            ("ayush.satmya", "Satmya"), ("ayush.sattva", "Sattva"),
            ("ayush.ahara_shakti", "Ahara Shakti"), ("ayush.vyayama_shakti", "Vyayama Shakti"),
            ("ayush.vaya", "Vaya"), ("ayush.agni", "Agni"), ("ayush.koshtha", "Koshtha"),
        ]:
            if _get(session, slot):
                ayush.append(f"{label}: {term(session.slots[slot])}")
        add(
            "ayush",
            "Dashavidha Pariksha",
            ayush,
            note=(
                "Abbreviated screen based on classical descriptions, not the CCRAS "
                "standardized Prakriti Assessment Scale. Sara, Samhanana and Pramana are "
                "patient-reported, not examination findings. Please confirm."
            ),
        )

        ahara = []
        for slot, label in [
            ("ahara.meal_regularity", "Meals"), ("ahara.rasa_preference", "Predominant rasa"),
            ("ahara.water_intake", "Water intake"), ("vihara.activity", "Activity"),
            ("vihara.sleep_pattern", "Sleep pattern"),
        ]:
            if _get(session, slot):
                ahara.append(f"{label}: {term(session.slots[slot])}")
        if _get(session, "vihara.stress") is not None:
            ahara.append(f"Reported stress: {session.slots['vihara.stress']}/10")
        add("ahara", "Ahara-Vihara", ahara)

    # 9 — Prior investigations
    docs_lines: list[str] = []
    docs_note = None
    if timeline and timeline.get("documents"):
        for doc in timeline["documents"]:
            when = doc["date"] or "date not readable"
            head = f"{when} — {doc['kind'].replace('_', ' ')}"
            if doc["diagnoses"]:
                head += f": {', '.join(doc['diagnoses'])}"
            docs_lines.append(head)
            for med in doc["medications"]:
                dose = " ".join(filter(None, [med.get("dose"), med.get("frequency")]))
                docs_lines.append(f"    {med['name']}{(' — ' + dose) if dose else ''}")
        for abn in timeline.get("abnormal_values", []):
            docs_lines.append(
                f"    ABNORMAL: {abn['analyte']} {abn['value']} {abn['unit'] or ''} "
                f"({abn['direction']}, ref {abn['ref_low']}-{abn['ref_high']})"
            )
        if timeline.get("interactions"):
            docs_note = "Interaction screening only — not a complete interaction check."
    elif session.slots.get("docs.has_papers") is False:
        docs_lines.append("Patient reported no prior documents")
    add("docs", "Prior investigations", docs_lines, note=docs_note)

    cov = coverage(ont, session)
    return {
        "session_id": session.id,
        "status": session.status,
        "generated_from": how,
        "patient": {
            "age_band": term(session.slots.get("identity.age_band")) if session.slots.get("identity.age_band") else None,
            "sex": term(session.slots.get("identity.sex")) if session.slots.get("identity.sex") else None,
            "respondent": session.slots.get("identity.respondent", "self"),
            "language": session.language,
        },
        "proxy_note": _proxy_note(session),
        "red_flag": session.red_flag,
        "sections": sections,
        "coverage": cov,
        "interactions": (timeline or {}).get("interactions", []),
        "abnormal_values": (timeline or {}).get("abnormal_values", []),
        "audit": session.audit,
        "elapsed_s": round(session.elapsed_s, 1),
        "budget_s": session.budget_s,
        "disclaimer": (
            "This is a patient-reported history captured before consultation. "
            "It contains no diagnosis and no clinical interpretation. "
            "Please verify, amend or reject before saving."
        ),
    }
