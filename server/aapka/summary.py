"""Module C — the physician-ready history.

Assembled from templates, not generated by a model. The section order is fixed by the
brief and reproduced exactly:

    Chief complaint -> HPI -> Past medical/surgical -> Drug & allergy -> Family
    -> Personal -> Review of systems -> Prior investigations

A model may be asked to smooth the HPI paragraph into readable prose, and that is the
only place one is allowed near this file. It is given the structured facts and told it
may not add to them; if it is unreachable, or if it returns anything that fails the
check below, the deterministic sentence is used instead. The summary therefore always
exists, always says the same things, and never contains a symptom the patient did not
report.

**This is a history, not an impression.** Nothing in this module names a disease,
ranks a differential, or suggests a next step. Hard rule 1, and the brief's own
words: "a draft to accept, amend, or reject, never an autonomous diagnosis."
"""

